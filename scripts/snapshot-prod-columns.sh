#!/usr/bin/env bash
# Regenerate supabase/prod-columns.json from the PRODUCTION database (#68).
#
# The manifest is what scripts/check-dashboard-columns.py validates dashboard
# `.select()` strings against. Run this when the production schema changes, and commit
# the diff so the change is reviewed like any other.
#
#   SUPABASE_ACCESS_TOKEN=$(security find-generic-password -s supabase-mgmt -a lumi -w) \
#     scripts/snapshot-prod-columns.sh
set -euo pipefail
: "${SUPABASE_ACCESS_TOKEN:?set SUPABASE_ACCESS_TOKEN (Management API PAT)}"
REF="${SUPABASE_PROJECT_REF:-cuaknazkpmwvnkmwtamp}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

SQL="select table_schema||'.'||table_name as t, string_agg(column_name,',' order by column_name) as cols from information_schema.columns where table_schema in ('public','orchestration') group by 1"
python3 -c "import json,sys; print(json.dumps({'query': sys.argv[1]}))" "$SQL" > /tmp/_snap_q.json

curl -sf -X POST \
  -H "Authorization: Bearer $SUPABASE_ACCESS_TOKEN" \
  -H "Content-Type: application/json" \
  --data-binary @/tmp/_snap_q.json \
  "https://api.supabase.com/v1/projects/$REF/database/query" \
| python3 -c "
import json, sys
rows = json.load(sys.stdin)
prod = {r['t']: sorted(r['cols'].split(',')) for r in rows}
out = {'_comment': ('Column manifest of the PRODUCTION database, per schema.table. Generated by '
                    'scripts/snapshot-prod-columns.sh. Used by scripts/check-dashboard-columns.py to '
                    'validate dashboard .select() strings, which TypeScript cannot check. Anchored to '
                    'production because that is what the dashboard actually queries -- NOT to a fresh '
                    'rebuild, which still creates stub shapes for the legacy tables (see #180).'),
       'tables': prod}
json.dump(out, open('$ROOT/supabase/prod-columns.json', 'w'), indent=2, sort_keys=True)
print(f\"  wrote supabase/prod-columns.json: {len(prod)} tables, {sum(len(v) for v in prod.values())} columns\")
"
rm -f /tmp/_snap_q.json
