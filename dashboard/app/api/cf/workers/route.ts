import { NextResponse } from "next/server";
import { createClient } from "@/lib/supabase/server";

const CF_BASE = "https://api.cloudflare.com/client/v4";
const CF_GQL = "https://api.cloudflare.com/client/v4/graphql";

export interface WorkerMetric {
  scriptName: string;
  requests: number;
  errors: number;
  /** Average CPU-time p50 over the window, in microseconds. */
  p50: number;
  /**
   * false = the script is deployed but returned no invocation data for the
   * window (never invoked, or its per-script query failed). The UI renders
   * these as an honest "no data" tile rather than a misleading "0 req · idle".
   */
  hasData: boolean;
}

/** Only real windows the UI offers; anything else falls back to 24h. */
function windowDays(raw: string | null): number {
  const n = Number(raw);
  return n === 7 || n === 30 ? n : 1;
}

/**
 * Per-Worker metrics for the Infrastructure worker grid.
 *
 * The worker list is NOT hardcoded: it is derived from Cloudflare's own list of
 * deployed scripts (`/workers/scripts`). That list is the runtime-visible
 * reflection of exactly what CI deploys — deploy-worker.yml globs every
 * runtime/workers/<agent>/wrangler.toml and deploys each, plus the runtime
 * worker — so a Tier-2 agent Worker generated by #67 appears here automatically
 * once it is deployed, with no code change. The dashboard is a separate
 * Cloudflare deployment and cannot read `runtime/` at build or request time, so
 * the deployed-scripts list is the correct runtime equivalent of that glob; it
 * also distinguishes "never deployed" (absent) from "deployed but not yet
 * invoked" (present, no data) exactly as the grid needs.
 *
 * We fan out one invocation query per script in parallel (Promise.allSettled),
 * reusing the same proven `scriptName:` filter the single-script metrics route
 * uses. A single `scriptName_in: [...]` query would be one round trip, but a
 * whole-query failure would blank the entire grid; per-script fan-out isolates
 * a failure or empty result to a single tile, which is what point 3 requires.
 */
export async function GET(req: Request): Promise<NextResponse> {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const accountId = process.env.CLOUDFLARE_ACCOUNT_ID ?? "";
  const token = process.env.CLOUDFLARE_API_TOKEN ?? "";
  if (!accountId || !token) {
    // Mirror the other cf routes so the client shows the same SetupCard.
    return NextResponse.json(
      { error: "CF credentials not configured" },
      { status: 503 },
    );
  }

  const headers = {
    "Content-Type": "application/json",
    Authorization: `Bearer ${token}`,
  };

  // 1. Deployed scripts → the canonical worker set (runtime + agents).
  const scriptsRes = await fetch(
    `${CF_BASE}/accounts/${accountId}/workers/scripts`,
    { headers },
  );
  if (!scriptsRes.ok) {
    const detail = await scriptsRes.text();
    return NextResponse.json(
      { error: `Cloudflare API error: ${scriptsRes.status}`, detail },
      { status: 502 },
    );
  }
  const scriptsBody = (await scriptsRes.json()) as { result?: Array<{ id?: string }> };
  const names = (scriptsBody.result ?? [])
    .map((s) => s.id ?? "")
    // Production lumiagents workers only: the runtime worker plus the agent
    // workers. Excludes `-staging` mirrors and non-agent scripts
    // (e.g. orchestration-workflow, which is not `lumiagents-*`).
    .filter((id) => id === "lumiagents-runtime" || (id.startsWith("lumiagents-") && !id.endsWith("-staging")))
    // Runtime first, then agents alphabetically — a stable, readable grid.
    .sort((a, b) => {
      if (a === "lumiagents-runtime") return -1;
      if (b === "lumiagents-runtime") return 1;
      return a.localeCompare(b);
    });

  const end = new Date();
  const start = new Date(Date.now() - windowDays(new URL(req.url).searchParams.get("days")) * 24 * 60 * 60 * 1000);

  // 2. One invocation query per script, in parallel.
  const settled = await Promise.allSettled(
    names.map(async (scriptName): Promise<WorkerMetric> => {
      const query = `{
  viewer {
    accounts(filter: {accountTag: "${accountId}"}) {
      workersInvocationsAdaptive(
        filter: {datetime_geq: "${start.toISOString()}", datetime_leq: "${end.toISOString()}", scriptName: "${scriptName}"}
        limit: 10000
      ) {
        sum { requests errors }
        quantiles { cpuTimeP50 }
      }
    }
  }
}`;
      const res = await fetch(CF_GQL, {
        method: "POST",
        headers,
        body: JSON.stringify({ query }),
      });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const body = (await res.json()) as {
        errors?: unknown[];
        data?: {
          viewer?: {
            accounts?: Array<{
              workersInvocationsAdaptive?: Array<{
                sum?: { requests?: number; errors?: number };
                quantiles?: { cpuTimeP50?: number };
              }>;
            }>;
          };
        };
      };
      if (body.errors && body.errors.length > 0) {
        throw new Error("GraphQL error");
      }
      const rows = body.data?.viewer?.accounts?.[0]?.workersInvocationsAdaptive ?? [];
      if (rows.length === 0) {
        return { scriptName, requests: 0, errors: 0, p50: 0, hasData: false };
      }
      const requests = rows.reduce((s, r) => s + (r.sum?.requests ?? 0), 0);
      const errors = rows.reduce((s, r) => s + (r.sum?.errors ?? 0), 0);
      const p50s = rows.map((r) => r.quantiles?.cpuTimeP50 ?? 0).filter((v) => v > 0);
      const p50 = p50s.length > 0 ? Math.round(p50s.reduce((s, v) => s + v, 0) / p50s.length) : 0;
      return { scriptName, requests, errors, p50, hasData: true };
    }),
  );

  // A rejected per-script query becomes a "no data" tile, never a blanked grid.
  const workers: WorkerMetric[] = settled.map((r, i) =>
    r.status === "fulfilled"
      ? r.value
      : { scriptName: names[i]!, requests: 0, errors: 0, p50: 0, hasData: false },
  );

  return NextResponse.json({ workers });
}
